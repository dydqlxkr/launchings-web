-- ─────────────────────────────────────────────
-- 1. reviews 테이블
-- ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.reviews (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  app_id     uuid NOT NULL REFERENCES public.apps(id) ON DELETE CASCADE,
  author_id  uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  rating     int  NOT NULL CHECK (rating >= 1 AND rating <= 5),
  body       text NOT NULL CHECK (char_length(body) >= 1 AND char_length(body) <= 1000),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (app_id, author_id)
);

CREATE INDEX IF NOT EXISTS idx_reviews_app ON public.reviews (app_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_reviews_author ON public.reviews (author_id);

-- ─────────────────────────────────────────────
-- 2. RLS
-- ─────────────────────────────────────────────
ALTER TABLE public.reviews ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "reviews_select_all"   ON public.reviews;
DROP POLICY IF EXISTS "reviews_insert_own"   ON public.reviews;
DROP POLICY IF EXISTS "reviews_update_own"   ON public.reviews;
DROP POLICY IF EXISTS "reviews_delete_own"   ON public.reviews;

-- 읽기: 공개
CREATE POLICY "reviews_select_all"
  ON public.reviews FOR SELECT USING (true);

-- 작성: 로그인 사용자, 본인 author_id
CREATE POLICY "reviews_insert_own"
  ON public.reviews FOR INSERT
  WITH CHECK (author_id = auth.uid());

-- 수정: 본인만
CREATE POLICY "reviews_update_own"
  ON public.reviews FOR UPDATE
  USING (author_id = auth.uid())
  WITH CHECK (author_id = auth.uid());

-- 삭제: 본인만
CREATE POLICY "reviews_delete_own"
  ON public.reviews FOR DELETE
  USING (author_id = auth.uid());

