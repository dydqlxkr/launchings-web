DELETE FROM public.apps
WHERE slug IN (
  'memoflow',
  'promptpilot',
  'harujaemu',
  'paletteai',
  'standupbot',
  'pixelquest',
  'codesnap',
  'habitloop',
  'mindmapai'
);

-- ─────────────────────────────────────────────────────────────
-- 2. 시드 프로필 삭제
--    apps 가 먼저 삭제된 후 profiles 를 삭제합니다.
--    handle 화이트리스트로만 삭제하므로 실제 가입 사용자에게 영향 없음.
-- ─────────────────────────────────────────────────────────────
